export function netLang() {
  try {
    return game.settings.get(NC_SCOPE, "nc.netLang") || "en";
  } catch (err) {
    return "en";
  }
}

/** Translate a UI string (falls back to the English text). */
export function T(text) {
  if (netLang() !== "th") return text;
  return TH[text] ?? text;
}

/** Keyed text with an English fallback (descriptions, hints, effects). */
export function TK(key, fallback) {
  if (netLang() !== "th") return fallback;
  return TH[key] ?? fallback;
}
